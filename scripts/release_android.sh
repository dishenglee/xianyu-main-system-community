#!/usr/bin/env bash
#
# Android release build for 鱼管家.
#
# Prerequisites (one-time):
#   - Android SDK + NDK installed (export ANDROID_HOME / NDK_HOME)
#   - Rust Android targets:
#       rustup target add aarch64-linux-android armv7-linux-androideabi \
#                         x86_64-linux-android i686-linux-android
#   - `cargo install tauri-cli --version ^2 --locked`
#   - Generate the Android project skeleton (run once per checkout):
#       cd src-tauri && cargo tauri android init
#
# Every subsequent build:
#   ./scripts/release_android.sh            # debug arm64 .apk
#   ./scripts/release_android.sh release    # release arm64 .apk
#
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

"$REPO_ROOT/scripts/check_release_version_consistency.py"

MODE="${1:-debug}"
FRONTEND_DIR="$REPO_ROOT/frontend-v2"
STATIC_DIR="${YUGUANJIA_STATIC_DIR:-${RELEASE_FRONTEND_DIST_DIR:-$REPO_ROOT/static}}"
TAURI_CONFIG_OVERRIDE="$(printf '{"build":{"beforeBuildCommand":"npm --prefix %s run build","frontendDist":"%s"}}' "$FRONTEND_DIR" "$STATIC_DIR")"
ANDROID_TAURI_TARGETS="${ANDROID_TAURI_TARGETS:-aarch64}"
read -r -a ANDROID_TARGET_ARGS <<<"$ANDROID_TAURI_TARGETS"

# -----------------------------------------------------------------------------
"$REPO_ROOT/scripts/ensure_frontend_deps.sh" "$FRONTEND_DIR"

release_version="$(
  python3 - <<'PY'
import pathlib
import re

text = pathlib.Path("Cargo.toml").read_text(encoding="utf-8")
match = re.search(r'^version\s*=\s*"([^"]+)"', text, re.MULTILINE)
if not match:
    raise SystemExit("failed to read release version from Cargo.toml")
print(match.group(1))
PY
)"

android_version_code="$(
  python3 - "$release_version" <<'PY'
import pathlib
import sys

version = sys.argv[1].strip()
versions = [
    line.strip()
    for line in pathlib.Path("docs/releases/known_versions.txt").read_text(encoding="utf-8").splitlines()
    if line.strip() and not line.strip().startswith("#")
]
if version not in versions:
    raise SystemExit(f"version {version} is not listed in docs/releases/known_versions.txt")
print(100000 + versions.index(version) + 1)
PY
)"
export YUGUANJIA_ANDROID_VERSION_NAME="$release_version"
export YUGUANJIA_ANDROID_VERSION_CODE="$android_version_code"
echo "  android version = $YUGUANJIA_ANDROID_VERSION_NAME ($YUGUANJIA_ANDROID_VERSION_CODE)"

# -----------------------------------------------------------------------------
# Sanity checks
# -----------------------------------------------------------------------------
if [[ -z "${ANDROID_HOME:-}" ]]; then
  echo "error: ANDROID_HOME not set" >&2
  exit 2
fi
if [[ -z "${NDK_HOME:-}${ANDROID_NDK_HOME:-}" ]]; then
  echo "warning: NDK_HOME / ANDROID_NDK_HOME not set — Gradle might still find one under \$ANDROID_HOME/ndk" >&2
fi
if [[ ! -d "$REPO_ROOT/src-tauri/gen/android" ]]; then
  echo "error: src-tauri/gen/android not found. First run: cd src-tauri && cargo tauri android init" >&2
  exit 2
fi

latest_android_build_tool() {
  local tool="$1"
  local path=""
  if [[ -d "$ANDROID_HOME/build-tools" ]]; then
    path="$(find "$ANDROID_HOME/build-tools" -maxdepth 2 -type f -name "$tool" | sort -V | tail -n 1)"
  fi
  if [[ -n "$path" ]]; then
    printf '%s\n' "$path"
  elif command -v "$tool" &>/dev/null; then
    command -v "$tool"
  else
    return 1
  fi
}

ANDROID_LOCAL_PROPERTIES="$REPO_ROOT/src-tauri/gen/android/local.properties"
{
  echo "# Generated by scripts/release_android.sh. Do not commit."
  echo "sdk.dir=$ANDROID_HOME"
  if [[ -n "${ANDROID_NDK_HOME:-${NDK_HOME:-}}" ]]; then
    echo "ndk.dir=${ANDROID_NDK_HOME:-$NDK_HOME}"
  fi
} >"$ANDROID_LOCAL_PROPERTIES"

refresh_tauri_android_settings() {
  local cargo_home="${CARGO_HOME:-$HOME/.cargo}"
  local tauri_android_dir=""

  if [[ -d "$cargo_home/registry/src" ]]; then
    tauri_android_dir="$(
      find "$cargo_home/registry/src" -type d -path '*/tauri-*/mobile/android' 2>/dev/null \
        | sort -V \
        | tail -n 1
    )"
  fi

  if [[ -z "$tauri_android_dir" || ! -d "$tauri_android_dir" ]]; then
    echo "error: cannot locate tauri mobile android project under $cargo_home/registry/src" >&2
    exit 2
  fi

  cat >"$REPO_ROOT/src-tauri/gen/android/tauri.settings.gradle" <<EOF
// THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
include ':tauri-android'
project(':tauri-android').projectDir = new File("$tauri_android_dir")
EOF
}

ensure_android_release_keystore() {
  local keytool_bin=""
  local sign_dir="${ANDROID_RELEASE_SIGN_DIR:-$HOME/.config/yuguanjia-build}"
  local env_file="${ANDROID_KEYSTORE_ENV_FILE:-$sign_dir/android-keystore.env}"

  if command -v keytool &>/dev/null; then
    keytool_bin="$(command -v keytool)"
  elif [[ -n "${JAVA_HOME:-}" && -x "${JAVA_HOME}/bin/keytool" ]]; then
    keytool_bin="${JAVA_HOME}/bin/keytool"
  else
    echo "error: keytool not found; install a JDK or export JAVA_HOME" >&2
    exit 2
  fi

  mkdir -p "$sign_dir"
  if [[ -f "$env_file" ]]; then
    # shellcheck disable=SC1090
    source "$env_file"
  fi

  export ANDROID_KEYSTORE_FILE="${ANDROID_KEYSTORE_FILE:-$sign_dir/android-release.keystore}"
  export ANDROID_KEY_ALIAS="${ANDROID_KEY_ALIAS:-yuguanjiarelease}"
  export ANDROID_KEYSTORE_PASSWORD="${ANDROID_KEYSTORE_PASSWORD:-$(openssl rand -hex 16)}"
  export ANDROID_KEY_PASSWORD="${ANDROID_KEY_PASSWORD:-$ANDROID_KEYSTORE_PASSWORD}"

  if [[ ! -f "$ANDROID_KEYSTORE_FILE" ]]; then
    echo "→ generating Android release keystore at $ANDROID_KEYSTORE_FILE"
    "$keytool_bin" \
      -genkeypair \
      -storetype PKCS12 \
      -keystore "$ANDROID_KEYSTORE_FILE" \
      -storepass "$ANDROID_KEYSTORE_PASSWORD" \
      -alias "$ANDROID_KEY_ALIAS" \
      -keypass "$ANDROID_KEY_PASSWORD" \
      -keyalg RSA \
      -keysize 2048 \
      -validity 3650 \
      -dname "CN=Yuguanjia, OU=Build, O=Disheng, L=Hangzhou, ST=Zhejiang, C=CN" \
      -noprompt
  fi

  cat >"$env_file" <<EOF
export ANDROID_KEYSTORE_FILE='$ANDROID_KEYSTORE_FILE'
export ANDROID_KEY_ALIAS='$ANDROID_KEY_ALIAS'
export ANDROID_KEYSTORE_PASSWORD='$ANDROID_KEYSTORE_PASSWORD'
export ANDROID_KEY_PASSWORD='$ANDROID_KEY_PASSWORD'
EOF
  chmod 600 "$env_file"
  echo "  android keystore = $ANDROID_KEYSTORE_FILE"
}

verify_android_release_signatures() {
  local apksigner_bin zipalign_bin
  apksigner_bin="$(latest_android_build_tool apksigner || true)"
  zipalign_bin="$(latest_android_build_tool zipalign || true)"

  if [[ -z "$apksigner_bin" || -z "$zipalign_bin" ]]; then
    echo "error: Android SDK build-tools apksigner/zipalign not found under $ANDROID_HOME/build-tools" >&2
    exit 2
  fi

  local apk_root="$REPO_ROOT/src-tauri/gen/android/app/build/outputs/apk"
  local artifact found=0

  while IFS= read -r artifact; do
    found=1
    echo "→ verifying signed APK $artifact"
    "$zipalign_bin" -c -p 4 "$artifact"
    "$apksigner_bin" verify --verbose --print-certs "$artifact"
  done < <(find "$apk_root" -type f -name '*release*.apk' 2>/dev/null | sort || true)

  if [[ "$found" == "0" ]]; then
    echo "error: no release APK artifacts found to verify" >&2
    exit 2
  fi
}

# -----------------------------------------------------------------------------
# Build
# -----------------------------------------------------------------------------
cd "$REPO_ROOT/src-tauri"
refresh_tauri_android_settings

case "$MODE" in
  debug)
    echo "→ cargo tauri android build --debug --apk --target ${ANDROID_TAURI_TARGETS}"
    cargo tauri android build \
      --debug \
      --apk \
      --target "${ANDROID_TARGET_ARGS[@]}" \
      -c "$TAURI_CONFIG_OVERRIDE"
    ;;
  release)
    ensure_android_release_keystore
    rm -rf "$REPO_ROOT/src-tauri/gen/android/app/build/outputs/bundle"
    echo "→ cargo tauri android build --apk --target ${ANDROID_TAURI_TARGETS}"
    cargo tauri android build \
      --apk \
      --target "${ANDROID_TARGET_ARGS[@]}" \
      -c "$TAURI_CONFIG_OVERRIDE"
    verify_android_release_signatures
    ;;
  *)
    echo "unknown mode: $MODE (expected 'debug' or 'release')" >&2
    exit 2 ;;
esac

echo
echo "✓ Android build complete. Artifacts under src-tauri/gen/android/app/build/outputs/"
